import sys, os, json, time, re
from pathlib import Path
from collections import defaultdict

sys.path.insert(0, os.path.abspath("."))

from src.document_processor.rag_pipeline import (
    VectorRetriever, LLMResponseGeneration, SIMILARITY_THRESHOLD, OLLAMA_MODEL
)

QUERIES_PATH = Path("tests/test_queries.json")
OUT_JSON     = Path("docs/finetuning_benchmark_sprint6.json")
OUT_MD       = Path("docs/finetuning_benchmark_sprint6.md")

STRATEGIES = ["baseline", "evidence_cited", "few_shot_cited"]

STOPWORDS = {
    "the","a","an","is","are","of","to","and","in","on","for","that","this",
    "it","as","with","be","by","or","which","was","were","its","at","from",
    "so","no","not","can","if","then","than","into","such"
}


def keyword_overlap(answer: str, expected: str) -> float:
    """Cheap, dependency-free proxy for answer quality: fraction of
    meaningful expected-answer words that also appear in the generated
    answer. Not a substitute for human grading, but gives a real, repeatable
    number for before/after comparison."""
    def words(s):
        return {w for w in re.findall(r"[a-z0-9\-]+", s.lower()) if w not in STOPWORDS and len(w) > 2}
    exp_words = words(expected)
    if not exp_words:
        return 0.0
    ans_words = words(answer)
    hit = exp_words & ans_words
    return round(len(hit) / len(exp_words), 3)


def citation_count(answer: str) -> int:
    return len(set(re.findall(r"\[S\d+\]", answer)))


def run_strategy(strategy: str, queries: list, retriever: VectorRetriever) -> dict:
    generator = LLMResponseGeneration(retriever=retriever, strategy=strategy)
    per_query = []
    for q in queries:
        t0 = time.time()
        resp = generator.generate(q["question"], top_k=5)
        latency = round(time.time() - t0, 3)

        expected = q.get("expected_answer", "")
        is_marker_category = q["category"] in ("off_topic", "ambiguous")

        if is_marker_category:
            # For these categories the "correct" behaviour is triggering the fallback / not confidently answering, not matching keywords.
            correct = bool(resp.is_fallback)
            kw_score = None
        else:
            correct = None
            kw_score = keyword_overlap(resp.answer, expected)

        per_query.append({
            "id": q["id"],
            "category": q["category"],
            "question": q["question"],
            "latency_s": latency,
            "is_fallback": resp.is_fallback,
            "confidence": resp.confidence,
            "confidence_score": resp.confidence_score,
            "citation_count": citation_count(resp.answer),
            "keyword_overlap": kw_score,
            "fallback_correct": correct,
        })
    return {"strategy": strategy, "model": OLLAMA_MODEL, "per_query": per_query}


def summarise(result: dict) -> dict:
    pq = result["per_query"]
    n = len(pq)
    factual = [r for r in pq if r["keyword_overlap"] is not None]
    marker  = [r for r in pq if r["fallback_correct"] is not None]

    def avg(vals):
        vals = [v for v in vals if v is not None]
        return round(sum(vals) / len(vals), 3) if vals else None

    return {
        "strategy": result["strategy"],
        "model": result["model"],
        "n_queries": n,
        "avg_latency_s": avg([r["latency_s"] for r in pq]),
        "avg_keyword_overlap_factual_hard": avg([r["keyword_overlap"] for r in factual]),
        "avg_citation_count": avg([r["citation_count"] for r in pq]),
        "avg_confidence_score": avg([r["confidence_score"] for r in pq]),
        "fallback_correct_rate_off_topic_ambiguous": (
            round(sum(1 for r in marker if r["fallback_correct"]) / len(marker), 3)
            if marker else None
        ),
    }


def write_markdown(summaries: list, path: Path):
    strat_names = [s["strategy"] for s in summaries]
    lines = [
        "Prompt Fine-Tuning Benchmark ",
        "",
        f"Model: `{OLLAMA_MODEL}`  |  Queries: {summaries[0]['n_queries']}",
        "",
        "Comparison of three prompt/generation configurations:",
        "- `baseline`: original prompt (no forced citations)",
        "- `evidence_cited`: New default: rules block + forced inline `[S#]` citations, "
        "generation params (temperature/top_p/num_predict) aligned to docs/prompt_strategy.md",
        "- `few_shot_cited`: Evidence_cited + one worked example",
        "",
        "Generated by `scripts/benchmark_finetuning.py`.",
        "",
        "| Metric | " + " | ".join(strat_names) + " |",
        "|---|" + "---:|" * len(strat_names),
    ]
    by_name = {s["strategy"]: s for s in summaries}
    rows = [
        ("Avg latency (s)", "avg_latency_s"),
        ("Avg keyword overlap vs expected answer (easy_factual + hard_reasoning)", "avg_keyword_overlap_factual_hard"),
        ("Avg distinct [S#] citations per answer", "avg_citation_count"),
        ("Avg retrieval confidence score", "avg_confidence_score"),
        ("Correct-fallback rate (off_topic + ambiguous)", "fallback_correct_rate_off_topic_ambiguous"),
    ]
    for label, key in rows:
        vals = [str(by_name[s][key]) for s in strat_names]
        lines.append(f"| {label} | " + " | ".join(vals) + " |")
    lines.append("")
    lines.append("Raw per-query results: `docs/finetuning_benchmark_sprint6.json`")
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    if not QUERIES_PATH.exists():
        print(f"ERROR: {QUERIES_PATH} not found. Run this from the project root.")
        sys.exit(1)

    queries = json.loads(QUERIES_PATH.read_text(encoding="utf-8"))
    print(f"Loaded {len(queries)} queries from {QUERIES_PATH}")

    print("\nLoading retriever (shared across both strategies, retrieval doesn't change)...")
    retriever = VectorRetriever()

    all_results, all_summaries = [], []
    for strat in STRATEGIES:
        print(f"\n=== Running strategy: {strat} ===")
        result = run_strategy(strat, queries, retriever)
        summary = summarise(result)
        all_results.append(result)
        all_summaries.append(summary)
        print(json.dumps(summary, indent=2))

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(
        {"summaries": all_summaries, "results": all_results}, indent=2
    ), encoding="utf-8")
    write_markdown(all_summaries, OUT_MD)

    print(f"\nSaved: {OUT_JSON}")
    print(f"Saved: {OUT_MD}")

    print(
        "\nNOTE: model outages, error responses and empty answers raise\n"
        "GenerationUnavailable and abort the run rather than scoring outage hints.\n"
        "Low confidence alone does not indicate an outage; inspect refusals and sources."
    )


if __name__ == "__main__":
    main()
